template<typename T> struct matrix : vector<vector<T>> {
	int n, m;

	void print() {
		for (int i = 0; i < n; i++) {
			for (int j = 0; j < m; j++) cout << (*this)[i][j] << " ";
			cout << endl;
		}
	}

	matrix(int n_, int m_, bool ident = false) :
			vector<vector<T>>(n_, vector<T>(m_, 0)), n(n_), m(m_) {
		if (ident) {
			assert(n == m);
			for (int i = 0; i < n; i++) (*this)[i][i] = 1;
		}
	}
	matrix(const vector<vector<T>>& c) : vector<vector<T>>(c),
		n(c.size()), m(c[0].size()) {}
	matrix(const initializer_list<initializer_list<T>>& c) {
		vector<vector<T>> val;
		for (auto& i : c) val.push_back(i);
		*this = matrix(val);
	}

	matrix<T> operator*(matrix<T>& r) {
		assert(m == r.n);
		matrix<T> M(n, r.m);
		for (int i = 0; i < n; i++) for (int k = 0; k < m; k++)
			for (int j = 0; j < r.m; j++) {
				T add = (*this)[i][k] * r[k][j];
#if MODULAR
#warning Usar matrix<ll> e soh colocar valores em [0, MOD) na matriz!
				M[i][j] += add%MOD;
				if (M[i][j] >= MOD) M[i][j] -= MOD;
#else
				M[i][j] += add;
#endif
			}
		return M;
	}
	matrix<T> operator^(ll e){
		matrix<T> M(n, n, true), at = *this;
		while (e) {
			if (e&1) M = M*at;
			e >>= 1;
			at = at*at;
		}
		return M;
	}
	void apply_transform(matrix M, ll e){
		auto& v = *this;
		while (e) {
			if (e&1) v = M*v;
			e >>= 1;
			M = M*M;
		}
	}
};

void solve() {
    int n, k; cin >> n >> k;
    vector<string> ss(k);
    for (auto& x : ss) cin >> x;
    // build the automaton, then walk on it N times
    vector<vector<int>> g = {vector<int>(26, -1)};
    map<string, int> mp;
    mp[""] = 0;
    vector<string> inv = {""};
    queue<int> q;
    q.push(0);
    auto kmp = [&] (string s) {
        vector<int> pi(sz(s));
        for (int i = 1, j = 0; i < sz(s); ++i) {
            while (j and s[i] != s[j]) j = pi[j-1];
            if (s[i] == s[j]) j++;
            pi[i] = j;
        }
        return pi;
    };
    while (!q.empty()) {
        int u = q.front(); q.pop();
        string eu = inv[u];
        for (int i = 0; i < 26; ++i) {
            eu += char(i + 'a');
            // find longest suffix which is a prefix for each string
            int mx = 0;
            bool bad = 0;
            for (int j = 0; j < k; ++j) {
                string s = ss[j] + "#" + eu;
                auto pi = kmp(s);
                ckmax(mx, pi.back());
                if (pi.back() == sz(ss[j])) bad = 1;
            }
            if (bad) { eu.pop_back(); continue; }
            string t;
            for (int j = sz(eu) - mx; j < sz(eu); ++j) t += eu[j];
            if (!mp.count(t)) {
                mp[t] = sz(inv);
                q.push(sz(inv));
                g.pb(vector<int>(26, -1));
                g[u][i] = sz(inv);
                inv.pb(t);
            } else g[u][i] = mp[t];
            eu.pop_back();
        }
    }
    int N = sz(g);
    matrix<mint> adj(N, N);
    for (int i = 0; i < N; ++i) {
        for (auto x : g[i]) if (x != -1) adj[i][x] += 1;
    }
    mint ans = 0;
    adj = adj^n; 
    for (int i = 0; i < N; ++i) ans += adj[0][i];
    cout << ans << endl;
}

