// SegTree
//
// Recursiva com Lazy Propagation
// Query: soma do range [a, b]
// Update: soma x em cada elemento do range [a, b]
// Pode usar a seguinte funcao para indexar os nohs:
// f(l, r) = (l+r)|(l!=r), usando 2N de memoria
//
// Complexidades:
// build - O(n)
// query - O(log(n))
// update - O(log(n))

const int MAX = 2e6;
namespace seg {
	ll seg[4*MAX+69], lazy[4*MAX+69];
	int n;

	ll build(int p=1, int l=0, int r=n-1) {
		lazy[p] = 0;
		if (l == r) return seg[p] = 0;
		int m = (l+r)/2;
		return seg[p] = build(2*p, l, m) + build(2*p+1, m+1, r);
	}
	void buildd(int n2) {
        n = n2;
		build();
	}
	ll query(int a, int b, int p=1, int l=0, int r=n-1) {
		if (a <= l and r <= b) return seg[p];
		if (b < l or r < a) return 0;
		int m = (l+r)/2;
		return max(query(a, b, 2*p, l, m), query(a, b, 2*p+1, m+1, r));
	}
	ll update(int a, int b, int x, int p=1, int l=0, int r=n-1) {
		if (a <= l and r <= b) {
        ckmax(seg[p], x);
			return seg[p];
		}
		if (b < l or r < a) return seg[p];
		int m = (l+r)/2;
		return seg[p] = max(update(a, b, x, 2*p, l, m),
			update(a, b, x, 2*p+1, m+1, r));
	}
};

// ultima posicao >= val em [a, b] (ou -1 se nao tem)
void solve() {
    int n; cin >> n;
    vector<int> t(n), pos(n);
    vector<ii> z(n);
    int shift = 1e6;
    for (int i = 0; i < n; ++i) {
        cin >> t[i] >> pos[i];
        z.pb({2*(t[i]+pos[i])+shift, 2*(t[i]-pos[i])+shift});
    }
    sort(all(z));
    seg::buildd(MAX-1);
    int ans = 0;
    for (int l = 0, r = 0; l < sz(z); l = r) {
        while (r != sz(z) and z[r].first == z[l].first) r++;
        vector<int> opts;
        for (int i = l; i < r; ++i) {
            opts.pb(1+seg::query(z[i].second+1, MAX-1));
            ckmax(ans, opts.back());
        }
        for (int i = l; i < r; ++i) {
            seg::update(z[i].second, z[i].second, opts[i-l]);
        }
    }
    cout << ans << endl;
}

