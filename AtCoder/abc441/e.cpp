void solve() {
    int n; cin >> n;
    string s; cin >> s;
    ord_set<ii> sexo;
    int ans = 0, cur = 0;
    sexo.insert({0, -1});
    for (int i = 0; i < n; ++i) {
        if (s[i] == 'A') {
            cur++;
        } else if (s[i] == 'B') {
            cur--;
        }
        ans += sexo.order_of_key({cur-1, inf});
        sexo.insert({cur, i});
    }
    cout << ans << endl;

}

